import { readFile, writeFile } from 'node:fs/promises';

const template = await readFile('email-templates/booking-confirmation.html', 'utf8');
const logo = await readFile('public/brand/kalisungan-logo.png');
const output = '// Generated by npm run email:sync from the reviewed HTML and brand logo.\n'
  + `export const bookingEmailTemplate = ${JSON.stringify(template)};\n`
  + `export const bookingEmailLogo = ${JSON.stringify(logo.toString('base64'))};\n`;
const path = 'supabase/functions/_shared/booking-email-template.ts';
const example = {
  logo_url: 'https://mtkali.vercel.app/brand/kalisungan-logo.png',
  to_name: 'Sample Hiker', hike_type: 'Morning', hike_date: 'October 12, 2026', hike_time: '06:00 AM PHT (UTC+8)',
  jump_off: 'Lamot 2 Jump-off', pax: '4', guide_name: 'Sample Guide', guide_contact: '+63 917 000 0000',
  reminder: 'Please call your assigned guide the day before your hike to confirm your meeting arrangements.',
  qr_code_url: 'https://quickchart.io/qr?text=PREVIEW-ONLY&size=220&margin=2',
  booking_reference: 'PREVIEW ONLY - not a real booking',
  route: 'Official Lamot 2 route', payment_status: 'Paid',
};
const preview = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
  if (!(key in example)) throw new Error(`Unknown preview field ${key}`);
  return example[key];
});
const previewPath = 'email-templates/booking-confirmation-preview.html';
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Email template differs from the server bundle. Run npm run email:sync.');
  if (await readFile(previewPath, 'utf8') !== preview) throw new Error('Email preview is stale. Run npm run email:sync.');
} else {
  await writeFile(path, output);
  await writeFile(previewPath, preview);
}
